import { minify } from 'html-minifier-next';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);

const options = {
    cacheCSS: 2000,
    cacheJS: 1000,
    caseSensitive: false,
    collapseAttributeWhitespace: true,
    collapseBooleanAttributes: true,
    collapseInlineTagWhitespace: true,
    collapseWhitespace: true,
    conservativeCollapse: false,
    continueOnMinifyError: true,
    continueOnParseError: true,
    decodeEntities: true,
    ignoreCustomComments: [],
    ignoreCustomFragments: ['<#[\\s\\S]*?#>', '<%[\\s\\S]*?%>', '<\\?[\\s\\S]*?\\?>'],
    includeAutoGeneratedTags: false,
    inlineCustomElements: [],
    keepClosingSlash: false,
    maxLineLength: 0,
    minifyCSS: true,
    minifyJS: { engine: 'swc', format: { comments: false } },
    minifySVG: true,
    removeUnusedCSS: { scripts: false },
    mergeScripts: true,
    partialMarkup: false,
    preserveLineBreaks: false,
    preventAttributesEscaping: true,
    processScripts: ['text/html', 'application/ld+json'],
    removeAttributeQuotes: true,
    removeComments: true,
    removeEmptyAttributes: true,
    removeEmptyElements: true,
    removeEmptyElementsExcept: [],
    removeOptionalTags: true,
    removeRedundantAttributes: true,
    removeDefaultTypeAttributes: true,
    removeTagWhitespace: false,
    sortAttributes: true,
    sortClassNames: true,
    trimCustomFragments: true,
    useShortDoctype: true,
};

export default async function (html, documentUrl) {
    return await minify(html, { ...options, minifyURLs: documentUrl || true });
}

export const { version } = require('../node_modules/html-minifier-next/package.json');
